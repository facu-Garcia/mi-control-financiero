const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const P=require('./features/ui/account-picker.js');
const account={id:'nu1',name:'Nu Crédito',type:'credit',institution:'Nu'};
assert.equal(P.typeLabel(account),'Crédito');
assert.equal(P.typeLabel({type:'pocket'}),'Cajita');
assert.equal(P.accountOf('nu1',[account]),account);
const safe=P.optionMarkup({value:'nu1',label:'Nu Crédito'},[account],'nu1');
assert.match(safe,/Nu Crédito/);
assert.match(safe,/aria-pressed="true"/);
assert.ok(!P.optionMarkup({value:'new',label:'<img src=x onerror=alert(1)>'},[],'').includes('<img src=x'));
const app=fs.readFileSync(path.join(__dirname,'app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'features/ui/account-picker.css'),'utf8');
assert.ok(app.includes('home-balance'));
assert.ok(app.includes('currentSavings()'));
assert.ok(app.includes('Planear mi mes'));
assert.ok(!app.includes('Tu dinero en tres respuestas'));
assert.ok(!app.includes('>Administrar suscripciones</button></div>'));
assert.ok(app.includes('function enhanceAccountPickers'));
assert.ok(app.includes("enhanceAccountPickers(modalInner)"));
assert.ok(html.indexOf('account-picker.js')<html.indexOf('app.js?v='));
assert.ok(html.includes('account-picker.css'));
assert.ok(css.includes('.ap-dialog'));
const dashboard=fs.readFileSync(path.join(__dirname,'features/dashboard/dashboard.js'),'utf8');
assert.ok(dashboard.includes("Dinero en débito y efectivo"));
assert.ok(dashboard.includes("Menos deuda de tarjetas"));
assert.ok(dashboard.includes("spendingPower"));
assert.ok(app.includes('recurrences:state.recurrences'));
console.log('✓ Selector de cuentas reutilizable, tarjetas, etiquetas y resumen sin duplicados');
