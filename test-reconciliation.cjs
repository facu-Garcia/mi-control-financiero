const assert=require('node:assert/strict');
const fs=require('node:fs');
const F=require('./logic.js');
const Forms=require('./features/finance/forms.js');
const app=fs.readFileSync('./app.js','utf8');
const account={id:'bank',type:'debit',balanceDate:'2026-11-20',initialBalance:10000};
const future={id:'later',type:'expense',accountId:'bank',date:'2026-11-24',amount:3000,months:1};
const old={id:'past',type:'expense',accountId:'bank',date:'2026-11-21',amount:1000,months:1};
assert.equal(F.accountBalance(account,[old,future].filter(m=>m.date<='2026-11-22')),9000);
assert.equal(F.accountBalance(account,[old,future]),6000);
const markup=Forms.reconcileForm(account,9000,x=>String(x),x=>String(x),x=>String(x),'2026-11-22');
assert.match(markup,/9000/);
assert.match(markup,/Captura el importe confirmado por tu banco/);
assert.match(markup,/name="actual"/);
assert.doesNotMatch(markup,/name="actual"[^>]*value=/);
assert.match(app,/state\.reconciliations\.filter\(r=>r\.accountId===a\.id\)/);
assert.match(app,/current!==r\.expected/);
assert.match(app,/document\.querySelector\('#reconcile-form \[name="actual"\]'\)\.value=''/);
assert.match(app,/if\(checkDate>localDate\(\)\)/);
console.log('✓ Conciliación: fecha histórica correcta, captura explícita y advertencia de histórico obsoleto');
