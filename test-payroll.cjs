const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const P=require('./features/payroll/payroll.js');
const V=require('./features/payroll/payroll-view.js');
const F=require('./logic.js');
const accounts=[{id:'debit1',type:'debit',name:'Cuenta de prueba',institution:'Banco genérico',initialBalance:10000,balanceDate:'2026-11-01'},
                {id:'credit',type:'credit',name:'Crédito',balanceDate:'2026-11-01',initialDebt:0}];
const profile={id:'debit1',accountId:'debit1',frequency:'semimonthly',day1:15,day2:31,expectedNet:810000};
assert.equal(P.validate(profile,accounts),profile);
assert.throws(()=>P.validate({...profile,accountId:'credit',id:'credit'},accounts),/débito/);
assert.throws(()=>P.validate({...profile,day1:30,day2:15},accounts),/anterior/);
assert.deepEqual(P.due(profile,'2026-02').map(x=>x.date),['2026-02-15','2026-02-28']);
assert.deepEqual(P.due(profile,'2028-02').map(x=>x.date),['2028-02-15','2028-02-29']);
assert.equal(P.due({...profile,frequency:'monthly',day1:31},'2026-04').length,1);
assert.equal(P.due({...profile,frequency:'monthly',day1:31},'2026-04')[0].date,'2026-04-30');
const first=P.due(profile,'2026-11')[0];
assert.equal(P.receiptFor(first,[]),null);
const salary={id:'salary1',type:'income',date:'2026-11-15',accountId:'debit1',toAccountId:'',amount:810000,months:1,category:'Ingresos',description:'Sueldo',payrollKind:'salary',payrollKey:first.key};
assert.equal(P.receiptFor(first,[salary]),salary);
assert.equal(P.receiptExists(first.key,[salary]),true);
assert.equal(P.receiptExists(first.key,[salary],'salary1'),false);
const benefit={id:'benefit',type:'income',date:'2026-11-22',accountId:'debit1',toAccountId:'',amount:120000,months:1,category:'Ingresos',description:'Aguinaldo',payrollKind:'christmasBonus',payrollKey:''};
assert.equal(F.breakdown(accounts,[salary,benefit],'2026-11').income,930000);
const totals=P.incomeTotals([salary,benefit],'debit1','2026-11');
assert.equal(totals.total,930000);assert.equal(totals.salary,810000);assert.equal(totals.extra,120000);
assert.equal(F.totals(accounts,[salary,benefit]).netWorth,940000);
assert.equal(P.incomeTotals([salary,benefit],'debit1','2026-12').total,0);
const format=x=>(x/100).toFixed(2),money=x=>'$'+format(x),esc=x=>String(x).replaceAll('<','&lt;');
const config=V.configForm(accounts,null,format,esc);
assert.match(config,/payroll-config-form/);assert.match(config,/p-account/);assert.ok(!config.includes('INBURSA'));
const register=V.registerForm(accounts[0],profile,null,'salary','salary','2026-11-15',profile.expectedNet,format,esc,P.TYPES,accounts);
assert.match(register,/payroll-receipt-form/);assert.match(register,/Fondo de ahorro/);
assert.ok(!register.includes('value="credit"'));
const classified=V.classifyForm(salary,profile,P,money,esc);
assert.match(classified,/sin duplicarlo/i);
const view=V.page(profile,accounts,[salary,benefit],'2026-11',P,money,esc,m=>m);
assert.match(view,/Nómina y prestaciones/);
assert.match(view,/Registrado/);assert.match(view,/Aguinaldo/);assert.match(view,/Primera quincena/);
