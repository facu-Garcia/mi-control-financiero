const assert=require('node:assert/strict');
const fs=require('node:fs');
const F=require('./logic.js');
const Report=require('./features/reports/report-model.js');
const View=require('./features/reports/report-view.js');
const accounts=[
 {id:'bank',name:'Banco',type:'debit',balanceDate:'2026-09-30',initialBalance:100000},
 {id:'save',name:'Ahorro',type:'saving',balanceDate:'2026-09-30',initialBalance:50000},
 {id:'card',name:'Tarjeta',type:'credit',balanceDate:'2026-09-30',initialDebt:30000,cutDay:20}
];
const moves=[
 {id:'salaryOct',type:'income',accountId:'bank',date:'2026-10-05',amount:50000},
 {id:'food',type:'expense',accountId:'bank',date:'2026-10-08',category:'Comida',amount:10000},
 {id:'newCard',type:'expense',accountId:'card',date:'2026-10-22',category:'Compras',amount:12000},
 {id:'payCard',type:'payment',accountId:'bank',toAccountId:'card',date:'2026-11-03',amount:8000},
 {id:'moveSave',type:'transfer',accountId:'bank',toAccountId:'save',date:'2026-11-04',amount:20000},
 {id:'salaryNov',type:'income',accountId:'bank',date:'2026-11-05',amount:40000},
 {id:'health',type:'expense',accountId:'card',date:'2026-11-10',category:'Salud',amount:5000},
 {id:'pending',type:'expense',accountId:'bank',date:'2026-11-11',category:'Servicios',amount:25000,autoGenerated:true,confirmed:false},
 {id:'future',type:'income',accountId:'bank',date:'2026-12-01',amount:99000}
];
const build=(opts={})=>Report.assemble({F,accounts,movements:moves,cycles:[],month:'2026-11',range:6,accountId:'all',today:'2026-11-22',...opts});
const report=build();
assert.equal(report.rows.length,6);
assert.equal(report.current.income,40000,'November income only');
assert.equal(report.current.purchases,17000,'credit purchase after October cut belongs in November');
assert.equal(report.current.payments,8000,'card payment distinct from new purchases');
assert.equal(report.current.cashChange,32000,'bank cash movement excludes internal transfer');
assert.equal(report.current.assets,222000);
assert.equal(report.current.debts,39000);
assert.equal(report.current.netWorth,183000);
assert.equal(report.totalIncome,90000);
assert.equal(report.totalPurchases,27000);
assert.equal(report.monthPurchases,17000);
assert.deepEqual(report.categories.map(c=>[c.name,c.amount]),[['Compras',12000],['Salud',5000]]);
assert.equal(report.items.length,2,'category drilldown excludes transfers, card payments and pending expenses');
assert.equal(report.rows[0].netWorth,null,'no invented historical data before baseline');
assert.equal(report.rows[3].netWorth,148000,'October snapshot from actual history');
assert.equal(report.current.partial,true,'current period labeled partial');
const credit=build({accountId:'card'});
assert.equal(credit.current.assets,0);
assert.equal(credit.current.debts,39000);
assert.equal(credit.current.payments,8000);
assert.equal(credit.current.income,0);
assert.equal(credit.current.purchases,17000);
assert.equal(credit.cards.length,1);
const debit=build({accountId:'bank'});
assert.equal(debit.current.debts,0);
assert.equal(debit.current.purchases,0);
assert.equal(debit.cards.length,0);
assert.equal(build({month:'2026-12'}).selectedIsFuture,true,'future period not presented as confirmed');
assert.equal(build({month:'2026-12'}).current.netWorth,null);
assert.throws(()=>build({range:8}),/Período|Periodo/);
assert.throws(()=>build({accountId:'unknown'}),/no existe/);
const E=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const M=c=>'$'+(c/100).toFixed(2);
const options={esc:E,money:M,monthName:s=>s,accounts,tab:'flow',range:6};
for(const tab of ['flow','categories','wealth','credit']){
  const html=View.render(report,{...options,tab});
  assert.match(html,/<h1>Mis informes<\/h1>/);
  assert.match(html,/report-range/);
  assert.match(html,/report-account/);
  assert.match(html,/report-tab/);
  assert.ok(!html.includes('undefined'));
}
assert.match(View.render(report,{...options,tab:'categories',category:'Compras'}),/Movimientos · Compras/);
assert.match(View.render(report,{...options,tab:'categories',category:'Compras'}),/12\.00/);
assert.match(View.render(credit,{...options,tab:'credit'}),/390\.00/);
assert.match(View.render(report,{...options,tab:'wealth',metric:'netWorth'}),/Evolución del patrimonio/);
const malicious=build({movements:[...moves,{id:'xss',type:'expense',accountId:'bank',date:'2026-11-12',category:'<img src=x onerror=alert(1)>',amount:100}]});
const escaped=View.render(malicious,{...options,tab:'categories'});
assert.ok(!escaped.includes('<img src=x onerror=alert(1)>'));
const index=fs.readFileSync('index.html','utf8'),app=fs.readFileSync('app.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(index.indexOf('report-model.js')<index.indexOf('app.js?v='));
assert.ok(index.indexOf('report-view.js')<index.indexOf('app.js?v='));
assert.ok(sw.includes('report-model.js?v=0.12.0'));
assert.match(app,/ReportModel\.assemble/);
assert.match(app,/reportTab='flow'/);
assert.match(app,/Versión 0\.12\.0/);
console.log('✓ Informes: ingresos vs compras, corte, crédito, pagos, patrimonio histórico, filtros, seguridad y PWA');
