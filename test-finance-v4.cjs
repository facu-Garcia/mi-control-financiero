const assert=require('node:assert/strict');
const F=require('./logic.js');
const R=require('./features/finance/recurring.js');
const I=require('./features/finance/insights.js');
const D=require('./features/dashboard/dashboard.js');
const V=require('./features/finance/forms.js');
const acc=[{id:'bbva',name:'BBVA',type:'debit',balanceDate:'2026-11-20',initialBalance:41513},
           {id:'credit',name:'Mercado Pago Crédito',type:'credit',cutDay:20,balanceDate:'2026-11-20',initialDebt:0}];
const salary={id:'salary',type:'income',accountId:'bbva',date:'2026-11-20',amount:41513,months:1};
assert.equal(F.breakdown(acc,[salary],'2026-11').income,41513);
assert.equal(F.totals(acc,[salary]).netWorth,41513);
assert.equal(I.baselineWarnings(acc,[salary]).length,1);
const noBase=[{...acc[0],initialBalance:0}];
assert.equal(F.totals(noBase,[salary]).netWorth,0);
const rule={id:'netflix',name:'Netflix',amount:19900,accountId:'bbva',frequency:'monthly',category:'Suscripciones',day:31,startDate:'2026-01-01',paused:false};
assert.equal(R.dueDate(rule,'2026-02'),'2026-02-28');
assert.equal(R.generate([rule],[],'2026-11-30').length,11);
const generated=R.generate([rule],[],'2026-11-30',1);
assert.equal(generated.length,1);
assert.equal(generated[0].autoGenerated,true);
assert.equal(generated[0].confirmed,false);
assert.equal(R.generate([rule],generated,'2026-11-30',1).length,0);
assert.equal(F.accountBalance(acc[0],generated),41513);
assert.equal(F.breakdown(acc,generated,'2026-11').purchases,0);
const confirmed={...generated[0],confirmed:true};
assert.equal(F.accountBalance(acc[0],[confirmed]),41513-19900);
assert.equal(F.breakdown(acc,[confirmed],'2026-11').purchases,19900);
const power=I.spendingPower(F,acc,generated,[rule],'2026-11-21');
assert.equal(power.liquid,41513);
assert.equal(power.spendable,41513-19900); // scheduled for 30 November
const html=D.render('income',{accounts:acc,movements:[salary],month:'2026-11',accountId:'all',F,I,esc:x=>String(x),money:x=>String(x),monthName:x=>x});
assert.match(html,/Ingresos recibidos/);
assert.match(html,/insight-account/);
const form=V.recurringForm(acc,null,x=>(x/100).toFixed(2),x=>String(x),'2026-11-21');
assert.match(form,/rec-form/);
const list=V.recurringPage([rule],generated,id=>acc.find(a=>a.id===id),String,String,'2026-11');
assert.match(list,/Confirmar cobro/);
assert.throws(()=>R.validate({...rule,day:32},acc),/día/);
console.log('✓ Saldos base, meses, cargos recurrentes idempotentes, saldos confirmados, vistas y formularios');
