const assert=require('node:assert/strict');
const fs=require('node:fs');
const Planning=require('./features/planning/planning.js');
const View=require('./features/planning/planning-view.js');
const F=require('./logic.js');
const Billing=require('./features/cards/billing.js');
const Payroll=require('./features/payroll/payroll.js');
const Rec=require('./features/finance/recurring.js');
const Pockets=require('./features/savings/pockets.js');
const deps={F,Billing,Payroll,Rec,Pockets};
const bank={id:'bank',type:'debit',name:'Cuenta',initialBalance:100000,balanceDate:'2026-11-01'};
const card={id:'cc',type:'credit',name:'Tarjeta',initialDebt:30000,balanceDate:'2026-11-01',cutDay:10,dueDay:25};
const pocket={id:'p1',parentAccountId:'bank',name:'Reservado',openingBalance:10000,createdDate:'2026-11-02'};
const rule={id:'fixed',name:'Renta',frequency:'monthly',accountId:'bank',amount:5000,day:28,startDate:'2026-11-01',endDate:'',paused:false};
const profile={id:'bank',accountId:'bank',frequency:'monthly',day1:30,day2:30,expectedNet:20000};
const data={accounts:[bank,card],movements:[],billingCycles:[],legacyInstallments:[],pockets:[pocket],
  pocketMoves:[],recurrences:[rule],payrollProfiles:[profile]};
const now='2026-11-22';
const res=Planning.capacity(data,deps,now,30);
assert.equal(res.liquid,100000);
assert.equal(res.reservedPockets,10000);
assert.equal(res.cardsDue,30000);
assert.equal(res.recurringDue,5000);
assert.equal(res.available,55000);
assert.equal(res.shortfall,0);
assert.equal(res.end,'2026-12-22');
const events=Planning.calendar(data,deps,'2026-11',now);
assert.ok(events.some(e=>e.kind==='card-payment'&&e.date==='2026-11-25'&&e.amount===30000));
assert.ok(events.some(e=>e.kind==='payroll'&&e.date==='2026-11-30'&&e.status==='estimated'));
assert.ok(events.some(e=>e.kind==='recurring'&&e.date==='2026-11-28'&&e.status==='planned'));
assert.ok(events.some(e=>e.kind==='card-cut'&&e.amount===0));
const receipt={id:'paycheck',type:'income',payrollKind:'salary',payrollKey:'bank|2026-11|1',
  accountId:'bank',date:'2026-11-30',amount:20000,months:1};
const planned=Planning.calendar({...data,movements:[receipt]},deps,'2026-11',now);
assert.ok(planned.some(e=>e.kind==='payroll'&&e.status==='recorded'));
assert.equal(Planning.capacity({...data,movements:[receipt]},deps,now,30).liquid,100000,
  'a future paycheck must not increase money available today');
const charge={id:'pending1',type:'expense',date:'2026-11-20',amount:5000,months:1,
  accountId:'bank',recurrenceId:'fixed',recurrenceMonth:'2026-11',autoGenerated:true,confirmed:false,description:'Renta'};
const pending=Planning.capacity({...data,movements:[charge]},deps,now);
assert.equal(pending.recurringDue,5000,'pending charge and rule count only once');
const confirmed=Planning.capacity({...data,movements:[{...charge,confirmed:true}]},deps,now);
assert.equal(confirmed.recurringDue,0);
assert.equal(confirmed.liquid,95000);
const payment={id:'payment',type:'payment',date:'2026-11-21',accountId:'bank',
  toAccountId:'cc',amount:10000,months:1};
const partly=Planning.capacity({...data,movements:[payment]},deps,now);
assert.equal(partly.liquid,90000);
assert.equal(partly.cardsDue,20000);
assert.equal(partly.available,55000,'paying a card does not improve net spendable twice');
const preexisting={id:'msi',type:'expense',date:'2026-11-11',accountId:'cc',months:3,amount:12000,category:'Compras'};
assert.equal(Planning.capacity({...data,movements:[preexisting]},deps,now).cardsDue,30000,
  'future MSI estimate must not double count the already outstanding cycle');
assert.equal(Planning.monthEnd('2028-02'),'2028-02-29');
assert.equal(Planning.plusDays('2026-12-31',1),'2027-01-01');
const twoMonthRule={...rule,startDate:'2026-12-01',day:4};
assert.equal(Planning.capacity({...data,recurrences:[twoMonthRule]},deps,now).recurringDue,5000);
const later=Planning.capacity({...data,recurrences:[{...rule,startDate:'2027-01-01'}]},deps,now,90);
assert.equal(later.recurringDue,10000,'90-day horizon traverses intervening months');
const lack=Planning.capacity({...data,accounts:[bank,{...card,dueDay:0}]},deps,now);
assert.ok(lack.warnings.some(x=>x.includes('sin fecha')));
assert.throws(()=>Planning.capacity(data,deps,'2026-11-31'),/inválida/);
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const markup=View.render(events,res,'2026-11',{esc,money:n=>'$'+(n/100).toFixed(2),monthName:()=> 'noviembre'});
assert.match(markup,/Calendario financiero/);
assert.match(markup,/Capacidad de pago/);
assert.match(markup,/550.00/);
assert.match(markup,/Pago de Tarjeta/);
const html=fs.readFileSync('./index.html','utf8');
const app=fs.readFileSync('./app.js','utf8');
const sw=fs.readFileSync('./sw.js','utf8');
assert.ok(html.indexOf('features/planning/planning.js')<html.indexOf('app.js?v='));
assert.ok(html.includes('planning-view.js'));
assert.ok(sw.includes('features/planning/planning.css?v=0.10.0'));
assert.match(app,/case 'open-planning':navigate\('planning'\)/);
assert.match(app,/function renderPlanning\(/);
assert.match(app,/Versión 0\.10\.0/);
console.log('✓ Planificación: cortes, vencimientos, nómina, MSI, ahorros, pendientes, histórico y navegación');
