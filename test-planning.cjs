const assert=require('node:assert/strict');
const fs=require('node:fs');
const Planning=require('./features/planning/planning.js');
const View=require('./features/planning/planning-view.js');
const F=require('./logic.js');
const Billing=require('./features/cards/billing.js');
const Payroll=require('./features/payroll/payroll.js');
const Rec=require('./features/finance/recurring.js');
const Pockets=require('./features/savings/pockets.js');
const deps={F,Billing,Payroll,Rec,Pockets},today='2026-11-22';
const bank={id:'bank',type:'debit',name:'Cuenta',initialBalance:213642,balanceDate:'2026-11-01'};
const nu={id:'nu',type:'credit',name:'Nu Crédito',initialDebt:372884,balanceDate:'2026-11-01',cutDay:26,dueDay:5};
const mp={id:'mp',type:'credit',name:'Mercado Pago Crédito',initialDebt:375646,balanceDate:'2026-11-01',cutDay:21,dueDay:1};
const profile={id:'bank',accountId:'bank',frequency:'semimonthly',day1:13,day2:28,expectedNet:813380};
const base={accounts:[bank,nu,mp],movements:[],billingCycles:[],recurrences:[],payrollProfiles:[profile],pockets:[],pocketMoves:[]};
const november=Planning.calendar(base,deps,'2026-11',today);
assert.equal(november.length,0,'no unconfirmed or estimated event counts as a real movement');
const refs=Planning.referenceEvents(base,deps,'2026-11',today);
assert.ok(refs.some(x=>x.kind==='salary'&&x.date==='2026-11-13'));
assert.ok(refs.some(x=>x.kind==='cut'&&x.date==='2026-11-26'));
assert.ok(refs.every(x=>x.status==='estimated'));
const scheduled=Planning.monthlyObligations(base,deps,'2026-11',today);
assert.equal(scheduled.total,0,'November must not list December deadlines');
const december=Planning.monthlyObligations(base,deps,'2026-12',today);
assert.equal(december.total,748530,'December debts are displayed in December');
assert.deepEqual(december.payments.map(p=>p.date),['2026-12-01','2026-12-05']);
assert.deepEqual(december.payments.map(p=>p.amount),[375646,372884]);
const capacity=Planning.capacity(base,deps,today);
assert.equal(capacity.liquid,213642);
assert.equal(capacity.cardsDue,748530);
assert.equal(capacity.shortfall,534888);
assert.equal(capacity.available,0);
const expense={id:'buy',type:'expense',date:'2026-11-21',accountId:'bank',amount:2000,description:'Comida'};
const pending={id:'pending',type:'expense',date:'2026-11-20',accountId:'bank',amount:3000,
  autoGenerated:true,confirmed:false,description:'Pendiente',recurrenceId:'rent',recurrenceMonth:'2026-11'};
const receipt={id:'check',type:'income',date:'2026-11-28',accountId:'bank',amount:813380,payrollKey:'bank|2026-11|2',payrollKind:'salary'};
const registered=Planning.calendar({...base,movements:[expense,pending,receipt]},deps,'2026-11',today);
assert.equal(registered.length,1);
assert.equal(registered[0].title,'Comida');
assert.equal(registered[0].date,'2026-11-21');
assert.equal(Planning.capacity({...base,movements:[receipt]},deps,today).liquid,213642,
  'future income does not create cash now');
const paid={id:'pay',type:'payment',date:'2026-11-22',accountId:'bank',toAccountId:'nu',amount:10000};
const partial=Planning.capacity({...base,movements:[paid]},deps,today);
assert.equal(partial.cardsDue,738530);
assert.equal(partial.liquid,203642);
assert.equal(partial.shortfall,534888);
const rule={id:'rent',name:'Renta',frequency:'monthly',accountId:'bank',amount:3000,day:20,startDate:'2026-11-01',paused:false};
const fixed=Planning.capacity({...base,recurrences:[rule],movements:[pending]},deps,today);
assert.equal(fixed.recurringDue,3000,'do not count auto-generated item and rule twice');
const confirmed=Planning.capacity({...base,recurrences:[rule],movements:[{...pending,confirmed:true}]},deps,today);
assert.equal(confirmed.recurringDue,0);
const laterMonth=Planning.monthlyObligations({...base,recurrences:[{...rule,day:4,startDate:'2027-01-01'}]},deps,'2027-02',today);
assert.equal(laterMonth.total,3000,'calendar is not restricted to 30-day range');
const oldMonth=Planning.calendar({...base,movements:[expense]},deps,'2026-10',today);
assert.equal(oldMonth.length,0);
assert.equal(Planning.monthEnd('2028-02'),'2028-02-29');
assert.equal(Planning.plusDays('2026-12-31',1),'2027-01-01');
assert.throws(()=>Planning.capacity(base,deps,'2026-11-31'),/inválida/);
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const markup=View.render(november,capacity,'2026-11',{
  esc,money:c=>'$'+(c/100).toFixed(2),monthName:()=> 'noviembre 2026',references:refs,monthly:scheduled});
assert.match(markup,/Noviembre 2026/);
assert.match(markup,/Movimientos registrados/);
assert.match(markup,/No hay movimientos efectivos/);
assert.match(markup,/30 días/);
assert.match(markup,/01\/12\/2026/);
assert.match(markup,/05\/12\/2026/);
assert.match(markup,/Faltante frente a compromisos/);
assert.match(markup,/Mostrar fechas de referencia/);
assert.doesNotMatch(markup,/Fecha o importe confirmado/);
const decemberHtml=View.render([],capacity,'2026-12',{esc,money:c=>'$'+(c/100).toFixed(2),monthName:()=> 'diciembre 2026',monthly:december});
assert.match(decemberHtml,/Pagos con vencimiento en diciembre 2026/);
assert.match(decemberHtml,/7485.30/);
const index=fs.readFileSync('./index.html','utf8'),app=fs.readFileSync('./app.js','utf8'),sw=fs.readFileSync('./sw.js','utf8');
assert.ok(index.indexOf('planning.js')<index.indexOf('app.js?v='));
assert.match(app,/Planning.monthlyObligations/);
assert.match(app,/Versión 0\.10\.1/);
assert.match(sw,/planning\.js\?v=0\.10\.1/);
console.log('✓ Agenda: hechos vs estimaciones, vencimientos noviembre/diciembre, sumas, calendario y móvil');
