const assert=require('node:assert/strict');
const CSV=require('./csv.js');
const F=require('./logic.js');
const headers='nombre,institucion,tipo,fecha_saldo,saldo_inicial,deuda_inicial,limite_credito,dia_corte,dia_pago';
const data=headers+'\n"Mercado Pago Crédito","Mercado Pago",credito,2026-11-20,0,0,0,20,\n"Nu Débito",Nu,débito,2026-11-20,125.50,0,0,,\n';
const parsed=CSV.accounts(data,[],'2026-11-20');
assert.equal(parsed.items.length,2);
assert.equal(parsed.items[0].cutDay,20);
assert.equal(parsed.items[0].creditLimit,0);
assert.equal(parsed.items[1].initialBalance,12550);
assert.equal(CSV.accounts(data,parsed.items,'2026-11-20').skipped,2);
assert.equal(CSV.amount('1,234.55'),123455);
assert.equal(CSV.amount('1234,55'),123455);
assert.equal(CSV.amount('0.01'),1);
assert.throws(()=>CSV.amount('1,23,456'),/inválido/);
assert.deepEqual(CSV.parse('a,b\n"hola, mundo","dice ""sí"""'),[{a:'hola, mundo',b:'dice "sí"'}]);
assert.deepEqual(CSV.parse('fecha;importe_mxn\n2026-11-20;12,25'),[{fecha:'2026-11-20',importe_mxn:'12,25'}]);
const [credit,debit]=parsed.items;
const records='fecha,tipo,cuenta,cuenta_destino,categoria,descripcion,importe_MXN,meses_MSI,referencia\n2026-10-21,gasto,Mercado Pago Crédito,,Compras,"Compra, online",600.00,3,REF1\n2026-11-19,ingreso,Nu Débito,,Otros,Nómina,2000.00,1,REF2';
const m=CSV.movements(records,parsed.items,[]);
assert.equal(m.items.length,2);assert.equal(F.statementCharges(credit,m.items,'2026-11').installments,20000);
assert.equal(CSV.movements(records,parsed.items,m.items).skipped,2);
assert.equal(CSV.movements(records.replace('REF1','REF2'),parsed.items,m.items).items.length,0);
console.log('✓ Importación CSV: cuentas, movimientos, duplicados, delimitadores, MSI y validación');
