const assert=require('node:assert/strict');
const fs=require('node:fs');
const F=require('./logic.js');
const B=require('./features/cards/billing.js');
const CSV=require('./csv.js');
const Drive=require('./drive-sync.js');

// Drive comparisons MUST include every persisted collection, independent of row order.
const base={kind:'complete-backup',schemaVersion:6,currency:'MXN',
 accounts:[{id:'b',initialBalance:50000}],movements:[],budgets:[],recurrences:[],
 reconciliations:[],audits:[],payrollProfiles:[],billingCycles:[],legacyInstallments:[],
 pockets:[],pocketMoves:[],settings:{id:'preferences',salary:0,savingsTarget:0}};
assert.ok(Drive.snapshotsEqual(base,JSON.parse(JSON.stringify(base))));
const keys=['accounts','movements','budgets','recurrences','reconciliations',
 'audits','payrollProfiles','billingCycles','legacyInstallments','pockets','pocketMoves'];
for(const key of keys){
 const modified=structuredClone(base);
 modified[key].push({id:'demo',accountId:'b',amount:100});
 assert.equal(Drive.snapshotsEqual(base,modified),false,key+' must trigger cloud conflict');
}
const changedSettings=structuredClone(base);changedSettings.settings.salary=100;
assert.equal(Drive.snapshotsEqual(base,changedSettings),false);
const rearranged=structuredClone(base);rearranged.accounts=[{id:'z'},{id:'a'}];
const reverse=structuredClone(rearranged);reverse.accounts.reverse();
assert.ok(Drive.snapshotsEqual(rearranged,reverse));

// CSV reordering and duplicate imports are idempotent, not tied to row index.
const bank={id:'b',name:'BBVA',type:'debit',institution:'',balanceDate:'2026-11-20',initialBalance:100000};
const header='fecha,tipo,cuenta,cuenta_destino,categoria,descripcion,importe_MXN,meses_MSI,referencia';
const r1='2026-11-21,gasto,BBVA,,Comida,café,70.00,1,';
const r2='2026-11-22,gasto,BBVA,,Comida,comida,80.00,1,';
const file=(...rows)=>[header,...rows].join('\n');
const first=CSV.movements(file(r1,r2),[bank],[]);
const second=CSV.movements(file(r2,r1),[bank],first.items);
assert.equal(first.items.length,2);
assert.equal(second.items.length,0);
assert.equal(second.skipped,2);
const doubles=CSV.movements(file(r1,r1),[bank],[]);
assert.equal(doubles.items.length,2);
assert.notEqual(doubles.items[0].id,doubles.items[1].id);
assert.equal(CSV.movements(file(r1,r1),[bank],doubles.items).skipped,2);
const legacy=first.items.map(m=>({...m,id:'csv-row:old'+m.id}));
assert.equal(CSV.movements(file(r2,r1),[bank],legacy).items.length,0);

// Historical reports never display a future movement as an older balance.
const futureIncome={id:'income',type:'income',date:'2026-12-05',accountId:'b',
 amount:50000,months:1,category:'Ingresos',description:'Salary'};
const nov=F.reportForMonth([bank],[futureIncome],{salary:0},'2026-11');
assert.equal(nov.accounts[0].balance,100000);
assert.equal(nov.asOf,'2026-11-30');
const laterAccount={...bank,id:'later',balanceDate:'2026-12-01'};
assert.equal(F.reportForMonth([laterAccount],[],{salary:0},'2026-11').accounts[0].balance,null);

// Historical MSI do not disappear when cut day has not been configured.
const credit={id:'cc',type:'credit',balanceDate:'2026-11-20',cutDay:0,dueDay:0,initialDebt:350000};
const oldMSI={id:'old',accountId:'cc',amount:300000,startMonth:'2026-12',endMonth:'2027-02',label:'Old MSI',includedInDebt:true};
assert.equal(F.statementCharges(credit,[],'2026-12',[],[oldMSI]).total,300000);
assert.equal(F.accountBalance(credit,[]),350000);
// Already-included installments do not inflate the headline payable.
const payable=B.paymentSummary(credit,'2026-12',[],[],[oldMSI],F);
assert.equal(payable.confirmed,350000);
assert.equal(payable.estimated,300000);
assert.equal(payable.total,350000);
// Virtual initial cut can legitimately receive a linked payment.
const initial=B.effectiveCycle(credit,'2026-11',[]);
const repayment={id:'pay',accountId:'b',toAccountId:'cc',type:'payment',
 amount:100000,date:'2026-11-25',paymentCycleId:initial.id};
assert.equal(B.officialRemaining(credit,initial,[repayment]),250000);
assert.equal(B.effectiveCycles(credit,[]).some(c=>c.id===repayment.paymentCycleId),true);

// UI hooks, backup validation, release assets.
const app=fs.readFileSync('./app.js','utf8');
const sw=fs.readFileSync('./sw.js','utf8');
assert.match(app,/Billing\.effectiveCycles\(dest,state\.billingCycles\)/);
assert.match(app,/Billing\.effectiveCycles\(idMap\.get\(m\.toAccountId\)/);
assert.match(app,/m\.autoGenerated&&!m\.confirmed/);
assert.match(app,/modificando el saldo o fecha inicial/);
assert.match(sw,/event\.request\.mode==='navigate'/);
console.log('✓ Auditoría: 12 colecciones, CSV idempotente, saldos históricos, MSI, cortes y PWA.');
