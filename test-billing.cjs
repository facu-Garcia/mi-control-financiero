const assert=require('node:assert/strict');
const fs=require('node:fs');
const F=require('./logic.js');
const B=require('./features/cards/billing.js');
const V=require('./features/cards/billing-view.js');
const card={id:'credit',name:'Tarjeta de prueba',type:'credit',cutDay:20,dueDay:10,initialDebt:800000,balanceDate:'2026-11-20',creditLimit:1500000};
const deb={id:'debit',name:'Cuenta de prueba',type:'debit',balanceDate:'2026-11-20',initialBalance:200000};
const accounts=[card,deb];
const cycle={id:'credit|2026-11',accountId:'credit',month:'2026-11',cutDate:'2026-11-21',dueDate:'2026-12-10',amountDue:350000};
assert.equal(B.validateCycle(cycle,accounts),cycle);
assert.equal(B.due(card,'2026-11',[cycle]).date,'2026-12-10');
assert.equal(B.cut(card,'2026-11',[cycle]).date,'2026-11-21');
assert.equal(B.cut(card,'2026-12',[]).date,'2026-12-20');
assert.equal(B.due(card,'2026-12',[]).date,'2027-01-10');
assert.throws(()=>B.validateCycle({...cycle,cutDate:'2026-12-01'},accounts),/dentro del mes/);
assert.throws(()=>B.validateCycle({...cycle,dueDate:'2026-11-20'},accounts),/posterior/);
assert.equal(B.daysUntil('2026-11-25','2026-11-21'),4);
assert.equal(F.statementOf('2026-11-21',20,[cycle],'credit'),'2026-11');
assert.equal(F.statementOf('2026-11-22',20,[cycle],'credit'),'2026-12');
const old={id:'older-msi',accountId:'credit',label:'Mensualidad ya existente',amount:300000,startMonth:'2026-12',endMonth:'2027-02'};
assert.equal(B.validateLegacy(old,accounts),old);
assert.equal(B.legacyFor('credit','2026-11',[old]),0);
assert.equal(B.legacyFor('credit','2026-12',[old]),300000);
assert.equal(B.legacyFor('credit','2027-03',[old]),0);
const purchase={id:'purchase',type:'expense',accountId:'credit',date:'2026-11-21',amount:150000,months:3,category:'Compras',description:'Producto'};
assert.equal(F.statementCharges(card,[purchase],'2026-11',[cycle],[old]).total,50000);
assert.equal(F.statementCharges(card,[purchase],'2026-12',[cycle],[old]).total,350000);
assert.equal(F.monthlyInstallments(accounts,[purchase],'2026-12',[cycle],[old]),350000);
assert.equal(F.accountBalance(card,[purchase]),800000+150000);
assert.equal(F.totals(accounts,[purchase]).debts,950000);
assert.equal(F.breakdown(accounts,[purchase],'2026-11',[cycle]).purchases,150000);
assert.equal(F.breakdown(accounts,[purchase],'2026-12',[cycle]).purchases,0);
const pay={id:'pay1',type:'payment',accountId:'debit',toAccountId:'credit',date:'2026-11-25',amount:100000};
assert.equal(B.officialRemaining(card,cycle,[pay]),250000);
assert.equal(B.dueCandidates(card,[cycle],[pay],'2026-11-26')[0].remaining,250000);
assert.equal(F.accountBalance(card,[purchase,pay]),850000);
assert.equal(F.accountBalance(deb,[pay]),100000);
const M=n=>'$'+(n/100).toFixed(2),E=x=>String(x).replaceAll('<','&lt;');
const form=V.form(card,cycle,B,n=>(n/100).toFixed(2),E,'2026-11');
assert.match(form,/Fecha exacta del corte/);assert.match(form,/Pago oficial/);
const legacy=V.legacyForm(card,old,B,n=>(n/100).toFixed(2),E,'2026-12');
assert.match(legacy,/Primer mes pendiente/);assert.match(legacy,/Último mes pendiente/);
const detail=V.detail(card,[cycle],[old],[purchase,pay],'2026-12','2026-11-26',B,F,M,E);
assert.match(detail,/MSI de compras anteriores/);
assert.match(detail,/3500.00/);
const alert=V.alert(card,[cycle],[pay],'2026-11-26',B,M,E);
assert.match(alert,/Pago del estado de cuenta/);
const app=fs.readFileSync('./app.js','utf8'),store=fs.readFileSync('./storage.js','utf8');
assert.match(app,/schemaVersion:5/);assert.match(app,/billingCycles:state.billingCycles/);
assert.match(app,/legacyInstallments:state.legacyInstallments/);
assert.match(app,/function cycleForm/);assert.match(app,/function legacyForm/);
assert.match(app,/data-payment-preset="total"/);assert.match(app,/data-payment-preset="statement"/);
assert.match(app,/savings-transfer/);
assert.match(store,/billingCycles/);assert.match(store,/legacyInstallments/);
console.log('✓ Cortes exactos, días variables, deuda, MSI heredados, pagos y respaldos seguros');