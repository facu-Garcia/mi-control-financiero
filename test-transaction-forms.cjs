const assert=require('node:assert/strict');
const fs=require('node:fs');
const Controller=require('./features/finance/transaction-forms.js');
const app=fs.readFileSync('./app.js','utf8');
const html=fs.readFileSync('./index.html','utf8');
const sw=fs.readFileSync('./sw.js','utf8');
const moduleText=fs.readFileSync('./features/finance/transaction-forms.js','utf8');
assert.equal(typeof Controller.create,'function');
assert.throws(()=>Controller.create({}),/getState/);
const forms=Controller.create({getState:()=>({accounts:[],movements:[],billingCycles:[],pockets:[]}),notify:()=>{}});
assert.equal(typeof forms.accountForm,'function');
assert.equal(typeof forms.movementForm,'function');
assert.match(app,/formController\.accountForm\(existing,preferredType\)/);
assert.match(app,/formController\.movementForm\(preferredAccountId,preferredType,existing,preferredDestination\)/);
assert.match(moduleText,/if\(existing\?\.pocketId\)/);
assert.match(moduleText,/modificando el saldo o fecha inicial/);
assert.ok(html.indexOf('transaction-forms.js')<html.indexOf('app.js?v='));
assert.ok(sw.includes('transaction-forms.js?v=0.11.1'));
assert.ok(html.indexOf('movement-picker.js')<html.indexOf('transaction-forms.js'));
assert.ok(html.includes('movement-picker.css?v=0.11.2'));
assert.ok(sw.includes('movement-picker.js?v=0.11.1'));
const pickerCss=fs.readFileSync('./features/ui/movement-picker.css','utf8');
assert.match(pickerCss,/grid-auto-rows:max-content/,'Las filas deben crecer con las descripciones');
assert.match(pickerCss,/min-height:0;grid-template-columns/,'El listado debe poder desplazarse dentro del modal');
assert.match(pickerCss,/\.mp-choice-copy\{flex:none/,'El texto de las tarjetas no debe desbordarse');
assert.doesNotMatch(pickerCss,/min-height:105px/,'No debe quedar la altura original insuficiente');
const picker=require('./features/ui/movement-picker.js');
assert.equal(typeof picker.enhance,'function');
assert.equal(picker.meta('type','expense').icon,'↗');
assert.equal(picker.meta('category','Transporte').icon,'🚇');
assert.match(picker.optionMarkup({value:'expense',textContent:'Gasto'},'type','expense'),/aria-pressed="true"/);
assert.ok(!picker.optionMarkup({value:'unsafe',textContent:'<img src=x>'},'category','').includes('<img'));
assert.match(moduleText,/FinanceMovementPicker\?\.enhance\(f\)/);
const modulePaths=[...html.matchAll(/<script src="(\.\/[^\"]+)" defer><\/script>/g)].map(m=>m[1].split('?')[0].slice(2));
for(const path of modulePaths)assert.ok(fs.existsSync(path),'Script inexistente: '+path);
console.log('✓ Formularios delegados, orden de carga, dependencias y compatibilidad con pruebas de auditoría');
