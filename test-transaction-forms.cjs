const assert=require('node:assert/strict');
const fs=require('node:fs');
const Controller=require('./features/finance/transaction-forms.js');
const app=fs.readFileSync('./app.js','utf8');
const html=fs.readFileSync('./index.html','utf8');
const sw=fs.readFileSync('./sw.js','utf8');
const moduleText=fs.readFileSync('./features/finance/transaction-forms.js','utf8');
assert.equal(typeof Controller.create,'function');
assert.throws(()=>Controller.create({}),/getState/);
const forms=Controller.create({getState:()=>({accounts:[],movements:[],billingCycles:[],pockets:[]}),notify:()=>{}});
assert.equal(typeof forms.accountForm,'function');
assert.equal(typeof forms.movementForm,'function');
assert.match(app,/formController\.accountForm\(existing,preferredType\)/);
assert.match(app,/formController\.movementForm\(preferredAccountId,preferredType,existing,preferredDestination\)/);
assert.match(moduleText,/if\(existing\?\.pocketId\)/);
assert.match(moduleText,/modificando el saldo o fecha inicial/);
assert.ok(html.indexOf('transaction-forms.js')<html.indexOf('app.js?v='));
assert.ok(sw.includes('transaction-forms.js?v=0.9.1'));
const modulePaths=[...html.matchAll(/<script src="(\.\/[^\"]+)" defer><\/script>/g)].map(m=>m[1].split('?')[0].slice(2));
for(const path of modulePaths)assert.ok(fs.existsSync(path),'Script inexistente: '+path);
console.log('✓ Formularios delegados, orden de carga, dependencias y compatibilidad con pruebas de auditoría');
