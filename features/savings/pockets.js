/* Internal savings allocations. A pocket is a subdivision of an existing bank account,
 * never an additional bank asset. All values are integer MXN cents. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.FinancePockets=api;})(typeof globalThis!=='undefined'?globalThis:this,()=>{
  const eligible=a=>a&&['debit','saving','cash'].includes(a.type);
  function validatePocket(p,accounts){
    if(!eligible(accounts.find(a=>a.id===p.parentAccountId)))throw Error('Elige una cuenta de dinero válida.');
    if(typeof p.name!=='string'||!p.name.trim()||p.name.length>80)throw Error('Escribe un nombre válido para la cajita.');
    if(!Number.isSafeInteger(p.openingBalance)||p.openingBalance<0||p.openingBalance>1e15)throw Error('Saldo reservado inválido.');
    if(typeof p.id!=='string'||!p.id||p.id.length>100)throw Error('Identificador inválido.');
    return p;
  }
  function balance(p,moves=[],movements=[]){
    let total=p.openingBalance||0;
    for(const m of moves){
      if(m.toPocketId===p.id)total+=m.amount;
      if(m.fromPocketId===p.id)total-=m.amount;
    }
    for(const m of movements){
      if(m.pocketId===p.id&&m.type==='yield'&&!(m.autoGenerated&&!m.confirmed)&&m.date>=(p.createdDate||'0000-01-01'))total+=m.amount;
    }
    return total;
  }
  function allocated(parentId,pockets=[],moves=[],movements=[]){
    return pockets.filter(p=>p.parentAccountId===parentId)
      .reduce((s,p)=>s+balance(p,moves,movements),0);
  }
  function totalAllocated(pockets=[],moves=[],movements=[]){
    return (pockets||[]).reduce((s,p)=>s+balance(p,moves,movements),0);
  }
  function available(account,bankBalance,pockets=[],moves=[],movements=[]){
    return bankBalance-allocated(account.id,pockets,moves,movements);
  }
  function validateMove(move,accounts,pockets,moves,movements,bankBalance){
    const account=accounts.find(a=>a.id===move.parentAccountId);
    if(!eligible(account))throw Error('Cuenta de origen inválida.');
    if(!Number.isSafeInteger(move.amount)||move.amount<=0)throw Error('El importe debe ser mayor a cero.');
    if(typeof move.date!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(move.date))throw Error('Fecha inválida.');
    if(move.fromPocketId===move.toPocketId)throw Error('Elige origen y destino distintos.');
    const parentPockets=pockets.filter(p=>p.parentAccountId===account.id);
    if(move.fromPocketId&&!parentPockets.some(p=>p.id===move.fromPocketId))throw Error('Cajita de origen inválida.');
    if(move.toPocketId&&!parentPockets.some(p=>p.id===move.toPocketId))throw Error('Cajita de destino inválida.');
    if(!move.fromPocketId&&!move.toPocketId)throw Error('Selecciona una cajita.');
    const sourceAmount=move.fromPocketId?
      balance(parentPockets.find(p=>p.id===move.fromPocketId),moves,movements):
      available(account,bankBalance,pockets,moves,movements);
    if(move.amount>sourceAmount)throw Error('El saldo asignable es insuficiente.');
    return move;
  }
  function validateSnapshot(accounts,pockets,moves,movements,F){
    const list=pockets||[], ids=new Set();
    for(const p of list){validatePocket(p,accounts);if(ids.has(p.id))throw Error('Cajita duplicada.');ids.add(p.id);}
    for(const m of moves||[]){
      if(!Number.isSafeInteger(m.amount)||m.amount<=0||!accounts.some(a=>a.id===m.parentAccountId))
        throw Error('Movimiento interno inválido.');
      for(const id of [m.fromPocketId,m.toPocketId])if(id&&!list.some(p=>p.id===id&&p.parentAccountId===m.parentAccountId))throw Error('La transferencia referencia una cajita inexistente.');
    }
    for(const a of accounts.filter(a=>eligible(a)&&list.some(p=>p.parentAccountId===a.id))){
      if(available(a,F.accountBalance(a,movements),list,moves,movements)<0)throw Error('Las cajitas de '+a.name+' superan su saldo bancario.');
      for(const p of list.filter(p=>p.parentAccountId===a.id)){
        if(balance(p,moves,movements)<0)throw Error('La cajita '+p.name+' tiene saldo negativo.');
      }
    }
    return true;
  }
  return {eligible,validatePocket,balance,allocated,totalAllocated,available,validateMove,validateSnapshot};
});