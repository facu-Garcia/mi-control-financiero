/* Monthly recurring transactions: deterministic, idempotent; pending until confirmed. */
(function(root,factory){const a=factory();if(typeof module==='object'&&module.exports)module.exports=a;else root.FinanceRecurring=a;})(typeof globalThis!=='undefined'?globalThis:this,()=>{
  function pad(n){return String(n).padStart(2,'0');}
  function monthShift(month,offset){
    const [year,m]=month.split('-').map(Number);
    const d=new Date(year,m-1+offset,1);
    return d.getFullYear()+'-'+pad(d.getMonth()+1);
  }
  function monthEnd(month){const [y,m]=month.split('-').map(Number);return new Date(y,m,0).getDate();}
  function dueDate(rule,month){return month+'-'+pad(Math.min(Number(rule.day)||1,monthEnd(month)));}
  function generate(rules,movements,today,limit=24){
    if(!/^\d{4}-\d{2}-\d{2}$/.test(today))throw Error('Fecha de generación inválida');
    const result=[],todayMonth=today.slice(0,7);
    const existing=new Set((movements||[]).filter(m=>m.recurrenceId).map(m=>m.recurrenceId+'|'+m.recurrenceMonth));
    for(const r of rules||[]){
      if(r.paused||r.frequency!=='monthly'||!r.accountId||!r.startDate||!Number.isSafeInteger(r.amount)||r.amount<=0)continue;
      const start=r.startDate.slice(0,7);
      for(let i=0;i<limit;i++){
        const m=monthShift(todayMonth,-i);
        if(m<start)break;
        if(r.endDate&&m>r.endDate.slice(0,7))continue;
        const day=dueDate(r,m);
        if(day<r.startDate||r.endDate&&day>r.endDate||day>today)continue;
        const key=r.id+'|'+m;
        if(existing.has(key))continue;
        existing.add(key);
        result.push({
          id:'rec-'+r.id+'-'+m,
          type:'expense',date:day,accountId:r.accountId,toAccountId:'',
          category:r.category||'Suscripciones',amount:r.amount,months:1,
          description:r.name||'Suscripción',
          recurrenceId:r.id,recurrenceMonth:m,
          autoGenerated:true,confirmed:false,createdAt:new Date().toISOString()
        });
      }
    }
    return result.sort((a,b)=>a.date.localeCompare(b.date));
  }
  function pending(m){return !!m.autoGenerated&&!m.confirmed;}
  function validate(rule,accounts){
    if(!rule.name||rule.name.length>80)throw Error('Agrega un nombre válido.');
    if(!accounts.some(a=>a.id===rule.accountId))throw Error('Selecciona una cuenta existente.');
    if(!Number.isSafeInteger(rule.amount)||rule.amount<=0)throw Error('El importe debe ser mayor a cero.');
    if(rule.frequency==='on-demand'||rule.kind==='frequent'){
      if(rule.frequency!=='on-demand')throw Error('Un gasto frecuente debe ser manual.');
      return rule;
    }
    if(rule.frequency!=='monthly')throw Error('Periodicidad no compatible.');
    if(!Number.isInteger(rule.day)||rule.day<1||rule.day>31)throw Error('El día de cobro debe estar entre 1 y 31.');
    if(!/^\d{4}-\d{2}-\d{2}$/.test(rule.startDate))throw Error('Fecha de inicio inválida.');
    if(rule.endDate&&rule.endDate<rule.startDate)throw Error('La fecha final no puede preceder al inicio.');
    return rule;
  }
  return {generate,pending,dueDate,monthShift,validate};
});