/* Domain service: financial insights, trends and conservative available-to-spend. No DOM access. */
(function(root,factory){const x=factory();if(typeof module==='object'&&module.exports)module.exports=x;else root.FinanceInsights=x;})(typeof globalThis!=='undefined'?globalThis:this,()=>{
  function currentDate(){const d=new Date();return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-');}
  function monthEnd(month){const [y,m]=month.split('-').map(Number);return [y,String(m).padStart(2,'0'),String(new Date(y,m,0).getDate()).padStart(2,'0')].join('-');}
  function active(m){return !(m.autoGenerated && m.confirmed!==true);}
  function snapshot(F,accounts,movements,day){
    if(accounts.some(a=>a.balanceDate>day))return null;
    return F.totals(accounts,movements.filter(m=>m.date<=day));
  }
  function monthlySeries(F,accounts,movements,month,count=6,cycles=[]){
    return Array.from({length:count},(_,i)=>{
      const key=F.shiftMonth(month,i-count+1),b=F.breakdown(accounts,movements,key,cycles);
      return {month:key,income:b.income,purchases:b.purchases,net:snapshot(F,accounts,movements,monthEnd(key))?.netWorth??null};
    });
  }
  function byAccount(accounts,movements,type){
    return accounts.filter(a=>!type||a.type===type).map(a=>({account:a,balance:0})); // caller decorates with F.accountBalance
  }
  function recurringDue(rules,movements,month){
    const result=[];
    const [y,m]=month.split('-').map(Number),last=new Date(y,m,0).getDate();
    for(const r of rules||[]){
      if(r.paused||r.frequency!=='monthly'||!r.startDate||r.startDate.slice(0,7)>month)continue;
      if(r.endDate&&r.endDate.slice(0,7)<month)continue;
      const day=Math.min(Number(r.day)||1,last),date=month+'-'+String(day).padStart(2,'0');
      if(date<r.startDate||r.endDate&&date>r.endDate)continue;
      const already=movements.some(v=>v.recurrenceId===r.id&&v.recurrenceMonth===month);
      if(!already)result.push({...r,dueDate:date});
    }
    return result;
  }
  function spendingPower(F,accounts,movements,recurrences,today=currentDate()){
    const totals=F.totals(accounts,movements);
    const liquid=accounts.filter(a=>a.type==='debit'||a.type==='cash').reduce((s,a)=>s+F.accountBalance(a,movements),0);
    const month=today.slice(0,7),scheduled=recurringDue(recurrences,movements,month).filter(r=>r.dueDate>=today&&accounts.find(a=>a.id===r.accountId)?.type!=='credit').reduce((sum,r)=>sum+r.amount,0);
    const pending=movements.filter(m=>m.autoGenerated&&!m.confirmed&&m.date>=today&&m.date.slice(0,7)===month&&accounts.find(a=>a.id===m.accountId)?.type!=='credit').reduce((sum,m)=>sum+m.amount,0);
    return {...totals,liquid,reservedDebt:Math.max(0,totals.debts),scheduled:scheduled+pending,spendable:Math.max(0,liquid-Math.max(0,totals.debts)-scheduled-pending)};
  }
  function baselineWarnings(accounts,movements){
    return accounts.map(a=>{
      const affected=movements.filter(m=>m.date<=a.balanceDate&&(m.accountId===a.id||m.toAccountId===a.id));
      return {account:a,count:affected.length,total:affected.reduce((s,m)=>s+m.amount,0)};
    }).filter(x=>x.count);
  }
  function forecast(F,accounts,movements,recurrences,salary,month,cycles=[],legacy=[]){
    const monthly=F.breakdown(accounts,movements,month,cycles);
    const known=recurringDue(recurrences,movements,month).reduce((s,r)=>s+r.amount,0);
    const pending=movements.filter(m=>m.autoGenerated&&!m.confirmed&&m.date.slice(0,7)===month).reduce((s,m)=>s+m.amount,0);
    const msi=F.monthlyInstallments(accounts,movements,month,cycles,legacy);
    return {incomePlan:salary||0,incomeReceived:monthly.income,scheduled:known+pending,msi,estimated:salary-known-pending-msi};
  }
  return {currentDate,monthEnd,active,snapshot,monthlySeries,byAccount,recurringDue,spendingPower,baselineWarnings,forecast};
});