/* Agenda financiera: distinguir hechos registrados de referencias y obligaciones.
 * Sin escritura de datos; importes en centavos enteros MXN. */
(function(root,factory){
  const api=factory();
  if(typeof module==='object'&&module.exports)module.exports=api;
  else root.FinancePlanning=api;
})(typeof globalThis!=='undefined'?globalThis:this,()=>{
  'use strict';
  const MONTH=/^\d{4}-(0[1-9]|1[0-2])$/;
  const DAY=/^\d{4}-(0[1-9]|1[0-2])-([0-2]\d|3[01])$/;
  const validDate=s=>typeof s==='string'&&DAY.test(s)&&!Number.isNaN(Date.parse(s+'T12:00:00Z'))&&new Date(s+'T12:00:00Z').toISOString().slice(0,10)===s;
  const list=a=>Array.isArray(a)?a:[];
  const sum=(rows)=>rows.reduce((s,x)=>s+x.amount,0);
  const atDate=(movements,today)=>list(movements).filter(m=>validDate(m.date)&&m.date<=today);
  function plusDays(date,n){
    if(!validDate(date))throw Error('Fecha inválida.');
    const d=new Date(date+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+n);return d.toISOString().slice(0,10);
  }
  function monthEnd(month){
    if(!MONTH.test(month))throw Error('Mes inválido.');
    const [year,num]=month.split('-').map(Number);
    return month+'-'+String(new Date(Date.UTC(year,num,0)).getUTCDate()).padStart(2,'0');
  }
  function calendar(data,_deps,month,today){
    if(!MONTH.test(month)||!validDate(today))throw Error('Mes o fecha inválida.');
    const accounts=list(data.accounts);
    // Sólo movimientos efectivos: los cargos automáticos pendientes y el ingreso previsto NO son hechos.
    const types=new Set(['expense','income','payment','transfer','yield']);
    return atDate(data.movements,today)
      .filter(m=>types.has(m.type)&&!(m.autoGenerated&&!m.confirmed)&&m.date.slice(0,7)===month)
      .map(m=>{
        const from=accounts.find(a=>a.id===m.accountId),to=accounts.find(a=>a.id===m.toAccountId);
        const names={expense:'Gasto',income:'Ingreso',payment:'Pago de tarjeta',transfer:'Transferencia',yield:'Rendimiento'};
        const title=m.description?.trim()||names[m.type];
        const detail=m.type==='payment'?'De '+(from?.name||'cuenta')+' a '+(to?.name||'tarjeta'):
          m.type==='transfer'?'Entre cuentas':from?.name||'Cuenta no disponible';
        return {id:'tx:'+m.id,date:m.date,kind:m.type,title,detail,amount:m.amount,
          status:'recorded',accountId:m.accountId};
      }).sort((a,b)=>b.date.localeCompare(a.date)||a.id.localeCompare(b.id));
  }
  function referenceEvents(data,deps,month,today){
    if(!MONTH.test(month)||!validDate(today))throw Error('Periodo inválido.');
    const refs=[],cycles=list(data.billingCycles);
    for(const card of list(data.accounts).filter(a=>a.type==='credit')){
      const cut=deps.Billing.cut(card,month,cycles);
      if(validDate(cut.date)){
        refs.push({id:'cut:'+card.id+':'+month,date:cut.date,kind:'cut',
          title:'Corte habitual · '+card.name,detail:cut.official?'Fecha capturada en la aplicación':'Calculada con el día habitual',
          status:cut.official?'captured':'estimated'});
      }
    }
    for(const p of list(data.payrollProfiles)){
      if(!list(data.accounts).some(a=>a.id===p.accountId))continue;
      for(const slot of deps.Payroll.due(p,month)){
        if(deps.Payroll.receiptFor(slot,list(data.movements)))continue;
        refs.push({id:'salary:'+slot.key,date:slot.date,kind:'salary',
          title:slot.label,detail:'Nómina prevista: no es un depósito registrado',
          amount:slot.expected,status:'estimated'});
      }
    }
    return refs.filter(e=>validDate(e.date)).sort((a,b)=>a.date.localeCompare(b.date)||a.id.localeCompare(b.id));
  }
  function occurrences(data,Rec,month){
    if(!MONTH.test(month))throw Error('Mes inválido.');
    const items=[],movements=list(data.movements),accounts=list(data.accounts);
    for(const r of list(data.recurrences)){
      if(r.frequency!=='monthly'||!r.startDate||!Number.isSafeInteger(r.amount)||r.amount<=0)continue;
      const recorded=movements.find(m=>m.recurrenceId===r.id&&m.recurrenceMonth===month);
      if(recorded){
        // La transacción confirmada ya está en el saldo; sólo se reserva la pendiente.
        if(recorded.autoGenerated&&!recorded.confirmed){
          items.push({id:'pending:'+recorded.id,date:recorded.date,kind:'recurring',title:recorded.description||r.name,
            amount:recorded.amount,accountId:recorded.accountId,status:'pending'});
        }
        continue;
      }
      if(r.paused)continue;
      const date=Rec.dueDate(r,month);
      if(date>=r.startDate&&(!r.endDate||date<=r.endDate)){
        items.push({id:'planned:'+r.id+':'+month,date,kind:'recurring',title:r.name||'Pago fijo',
          amount:r.amount,accountId:r.accountId,status:'planned'});
      }
    }
    // Sigue pendiente aunque se haya eliminado la regla original.
    for(const m of movements.filter(m=>m.type==='expense'&&m.autoGenerated&&!m.confirmed&&m.date?.slice(0,7)===month)){
      if(!items.some(x=>x.id==='pending:'+m.id))items.push({id:'pending:'+m.id,date:m.date,kind:'recurring',
        title:m.description||'Cargo por confirmar',amount:m.amount,accountId:m.accountId,status:'pending'});
    }
    return items.map(x=>({...x,accountType:accounts.find(a=>a.id===x.accountId)?.type||''}));
  }
  function monthPayments(data,deps,month,today){
    if(!MONTH.test(month)||!validDate(today))throw Error('Periodo inválido.');
    const tx=atDate(data.movements,today),cycles=list(data.billingCycles),items=[];
    let unknown=0;
    for(const card of list(data.accounts).filter(a=>a.type==='credit')){
      const effective=deps.Billing.effectiveCycles(card,cycles);
      for(const c of effective){
        const due=validDate(c.dueDate)?c.dueDate:deps.Billing.due(card,c.month,cycles).date;
        const remaining=deps.Billing.officialRemaining(card,c,tx,effective);
        if(!Number.isSafeInteger(remaining)||remaining<=0)continue;
        if(!validDate(due)){unknown++;continue;}
        if(due.slice(0,7)!==month)continue;
        const captured=cycles.some(saved=>saved.id===c.id&&saved.amountDue!=null);
        items.push({id:'due:'+c.id,date:due,kind:'card-payment',title:card.name,
          amount:remaining,cycleMonth:c.month,accountId:card.id,status:captured?'captured':'estimated',
          overdue:due<today,detail:captured?'Importe de corte capturado':'Saldo inicial estimado; verifica con tu banco'});
      }
      if(!effective.some(c=>c.amountDue!=null)&&deps.F.accountBalance(card,tx)>0)unknown++;
    }
    items.sort((a,b)=>a.date.localeCompare(b.date)||a.title.localeCompare(b.title));
    return {month,items,unknown};
  }
  function monthlyObligations(data,deps,month,today){
    const payments=monthPayments(data,deps,month,today);
    const recurringItems=occurrences(data,deps.Rec,month).filter(e=>e.accountType!=='credit'&&
      (e.status==='pending'||e.status==='planned'&&e.date>=today));
    return {payments:payments.items,recurringItems,
      total:sum(payments.items)+sum(recurringItems),unknown:payments.unknown};
  }

  // Mostrar el importe asociado al ciclo de corte sin crear otra transacción.
  function statementCommitments(data,deps,month,today){
    if(!MONTH.test(month)||!validDate(today))throw Error('Periodo inválido.');
    const tx=atDate(data.movements,today),cycles=list(data.billingCycles),items=[];
    for(const card of list(data.accounts).filter(a=>a.type==='credit')){
      const effective=deps.Billing.effectiveCycles(card,cycles);
      for(const c of effective.filter(c=>c.month===month)){
        const remaining=deps.Billing.officialRemaining(card,c,tx,effective);
        if(!Number.isSafeInteger(remaining)||remaining<=0)continue;
        const due=validDate(c.dueDate)?c.dueDate:deps.Billing.due(card,month,cycles).date;
        const cut=validDate(c.cutDate)?c.cutDate:deps.Billing.cut(card,month,cycles).date;
        const captured=cycles.some(saved=>saved.id===c.id&&saved.amountDue!=null);
        items.push({id:'statement:'+c.id,accountId:card.id,kind:'statement',title:card.name,
          amount:remaining,cycleMonth:month,cutDate:validDate(cut)?cut:'',
          dueDate:validDate(due)?due:'',source:c.source||'bank',
          status:captured?'captured':'estimated'});
      }
    }
    items.sort((a,b)=>(a.dueDate||'9999').localeCompare(b.dueDate||'9999')||a.title.localeCompare(b.title));
    // El saldo inicial no equivale a compras nuevas registradas.
    const purchases=deps.F.breakdown(list(data.accounts),tx,month,cycles).purchases;
    return {month,items,total:sum(items),purchases};
  }
  function upcomingPayments(data,deps,today,days=30){
    if(!validDate(today))throw Error('Fecha inválida.');
    if(!Number.isInteger(days)||days<1||days>90)throw Error('Horizonte inválido.');
    const end=plusDays(today,days),items=[];let unknown=0;
    // Fecha límite, no fecha de corte. Incluye compromisos atrasados aún abiertos.
    const months=new Set();
    for(const c of list(data.billingCycles)){if(c.dueDate&&c.dueDate<=end)months.add(c.dueDate.slice(0,7));}
    for(let month=today.slice(0,7);month<=end.slice(0,7);month=deps.F.shiftMonth(month,1))months.add(month);
    // También incluir vencidos anteriores de ciclos de deuda inicial.
    for(const card of list(data.accounts).filter(a=>a.type==='credit')){
      for(const c of deps.Billing.effectiveCycles(card,list(data.billingCycles))){
        const due=c.dueDate||deps.Billing.due(card,c.month,list(data.billingCycles)).date;
        if(due&&due<=end)months.add(due.slice(0,7));
      }
    }
    for(const month of months){
      const period=monthPayments(data,deps,month,today);
      unknown=Math.max(unknown,period.unknown);
      for(const p of period.items)if(p.date<=end)items.push(p);
    }
    const unique=[...new Map(items.map(p=>[p.id,p])).values()].sort((a,b)=>a.date.localeCompare(b.date));
    return {end,items:unique,unknown};
  }
  function capacity(data,deps,today,days=30){
    if(!validDate(today))throw Error('Fecha inválida.');
    if(!Number.isInteger(days)||days<1||days>90)throw Error('Horizonte inválido.');
    const payments=upcomingPayments(data,deps,today,days),end=payments.end;
    const accounts=list(data.accounts),tx=atDate(data.movements,today);
    const liquid=accounts.filter(a=>['debit','cash'].includes(a.type)&&a.balanceDate<=today)
      .reduce((s,a)=>s+deps.F.accountBalance(a,tx),0);
    const pockets=list(data.pockets).filter(p=>p.createdDate<=today&&accounts.some(a=>a.id===p.parentAccountId&&['debit','cash'].includes(a.type)));
    const reservedPockets=Math.max(0,deps.Pockets.totalAllocated(pockets,list(data.pocketMoves).filter(m=>m.date<=today),tx));
    const recurringItems=[];
    for(let month=today.slice(0,7);month<=end.slice(0,7);month=deps.F.shiftMonth(month,1)){
      for(const e of occurrences(data,deps.Rec,month)){
        if(e.accountType==='credit')continue;
        if((e.status==='planned'&&e.date>=today||e.status==='pending')&&e.date<=end){
          recurringItems.push(e);
        }
      }
    }
    const cardsDue=sum(payments.items),recurringDue=sum(recurringItems);
    const rawAvailable=liquid-reservedPockets-cardsDue-recurringDue;
    const warnings=[];
    if(payments.unknown)warnings.push('Hay '+payments.unknown+' obligaciones de tarjeta sin fecha o monto asignable. Verifica los estados de cuenta; no están incluidas en el cálculo.');
    if(accounts.some(a=>['debit','cash'].includes(a.type)&&a.balanceDate>today))warnings.push('Algunas cuentas tienen fecha inicial futura y no se incluyen en el efectivo.');
    if(payments.items.some(p=>p.status==='estimated'))warnings.push('Algunos pagos se derivan de deudas iniciales; sus importes o fechas todavía deben contrastarse con el banco.');
    return {today,end,days,liquid,reservedPockets,cardsDue,recurringDue,
      obligations:cardsDue+recurringDue,available:Math.max(0,rawAvailable),shortfall:Math.max(0,-rawAvailable),
      paymentItems:payments.items,recurringItems,warnings,unknownPayments:payments.unknown};
  }
  return {plusDays,monthEnd,calendar,referenceEvents,occurrences,monthPayments,monthlyObligations,statementCommitments,upcomingPayments,capacity};
});
