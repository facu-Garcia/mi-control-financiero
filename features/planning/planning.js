/* Calendario y capacidad de pago: sólo lectura sobre datos financieros privados.
 * Montos en centavos. Las proyecciones JAMÁS registran movimientos ni suman saldos. */
(function(root,factory){
  const api=factory();
  if(typeof module==='object'&&module.exports)module.exports=api;
  else root.FinancePlanning=api;
})(typeof globalThis!=='undefined'?globalThis:this,()=>{
  'use strict';
  const monthPattern=/^\d{4}-(0[1-9]|1[0-2])$/;
  const datePattern=/^\d{4}-(0[1-9]|1[0-2])-([0-2]\d|3[01])$/;
  const validDate=s=>datePattern.test(s)&&!Number.isNaN(Date.parse(s+'T12:00:00Z'))&&new Date(s+'T12:00:00Z').toISOString().slice(0,10)===s;
  function plusDays(date,n){
    if(!validDate(date))throw Error('Fecha inválida.');
    const d=new Date(date+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+n);return d.toISOString().slice(0,10);
  }
  function monthEnd(month){
    if(!monthPattern.test(month))throw Error('Mes inválido.');
    const [y,m]=month.split('-').map(Number);
    return month+'-'+String(new Date(Date.UTC(y,m,0)).getUTCDate()).padStart(2,'0');
  }
  const empty=k=>Array.isArray(k)?k:[];
  const asOf=(movements,date)=>empty(movements).filter(m=>validDate(m.date)&&m.date<=date);
  function occurrences(data,Rec,month){
    const rules=empty(data.recurrences),tx=empty(data.movements),accounts=empty(data.accounts);
    const result=[];
    for(const r of rules){
      if(r.frequency!=='monthly'||!r.startDate||!monthPattern.test(month)||!Number.isSafeInteger(r.amount)||r.amount<=0)continue;
      const date=Rec.dueDate(r,month);
      const recorded=tx.find(m=>m.recurrenceId===r.id&&m.recurrenceMonth===month);
      if(recorded){
        result.push({id:'rec:'+recorded.id,date:recorded.date,kind:'recurring',title:recorded.description||r.name,
          amount:recorded.amount,accountId:recorded.accountId,status:recorded.autoGenerated&&!recorded.confirmed?'pending':'recorded'});
      }else if(!r.paused&&date>=r.startDate&&(!r.endDate||date<=r.endDate)){
        result.push({id:'plan:'+r.id+':'+month,date,kind:'recurring',title:r.name||'Pago fijo',
          amount:r.amount,accountId:r.accountId,status:'planned'});
      }
    }
    // Un cargo pendiente permanece exigible aunque la regla original se haya eliminado.
    for(const m of tx.filter(m=>m.autoGenerated&&!m.confirmed&&m.type==='expense'&&m.date?.slice(0,7)===month)){
      if(!result.some(e=>e.id==='rec:'+m.id))result.push({id:'rec:'+m.id,date:m.date,kind:'recurring',
        title:m.description||'Cargo pendiente',amount:m.amount,accountId:m.accountId,status:'pending'});
    }
    return result.map(e=>({...e,accountType:accounts.find(a=>a.id===e.accountId)?.type||''}));
  }
  function cardRows(data,{Billing,F},month,today){
    const rows=[],tx=asOf(data.movements,today),cards=empty(data.accounts).filter(a=>a.type==='credit');
    for(const card of cards){
      const cycles=Billing.effectiveCycles(card,empty(data.billingCycles));
      for(const c of cycles.filter(c=>c.dueDate?.slice(0,7)===month)){
        const remaining=Billing.officialRemaining(card,c,tx,cycles);
        rows.push({id:'due:'+c.id,date:c.dueDate,kind:'card-payment',title:'Pago de '+card.name,
          amount:Math.max(0,remaining||0),status:remaining===0?'paid':c.estimated?'estimated':'confirmed',
          accountId:card.id,detail:c.estimated?'Deuda inicial registrada':'Estado de cuenta; saldo pendiente al día de hoy'});
      }
      const cut=Billing.cut(card,month,empty(data.billingCycles));
      if(cut.date){
        const recorded=cycles.some(c=>c.month===month);
        const estimate=!recorded?F.statementCharges(card,empty(data.movements),month,empty(data.billingCycles),empty(data.legacyInstallments)).total:0;
        rows.push({id:'cut:'+card.id+':'+month,date:cut.date,kind:'card-cut',title:'Corte de '+card.name,
          amount:estimate,status:cut.official?'confirmed':'estimated',detail:estimate?'Cargos previstos (informativos; no sumar al pago)':'Fecha de corte'});
      }
    }
    return rows;
  }
  function calendar(data,deps,month,today){
    if(!monthPattern.test(month)||!validDate(today))throw Error('Fecha del calendario inválida.');
    const events=[...occurrences(data,deps.Rec,month),...cardRows(data,deps,month,today)];
    for(const p of empty(data.payrollProfiles)){
      if(!empty(data.accounts).some(a=>a.id===p.accountId))continue;
      for(const slot of deps.Payroll.due(p,month)){
        const receipt=deps.Payroll.receiptFor(slot,empty(data.movements));
        events.push({id:'salary:'+slot.key,date:slot.date,kind:'payroll',title:slot.label,
          amount:receipt?.amount??slot.expected,status:receipt?'recorded':'estimated',accountId:p.accountId,
          detail:receipt?'Ingreso vinculado registrado':'Ingreso previsto; no suma al saldo hasta registrarlo'});
      }
    }
    return events.filter(e=>validDate(e.date)&&e.date.slice(0,7)===month)
      .sort((a,b)=>a.date.localeCompare(b.date)||a.kind.localeCompare(b.kind)||a.id.localeCompare(b.id));
  }
  function capacity(data,deps,today,days=30){
    if(!validDate(today)||!Number.isInteger(days)||days<1||days>90)throw Error('Horizonte inválido.');
    const end=plusDays(today,days),accounts=empty(data.accounts),movements=asOf(data.movements,today);
    const liquid=accounts.filter(a=>['debit','cash'].includes(a.type)&&a.balanceDate<=today)
      .reduce((sum,a)=>sum+deps.F.accountBalance(a,movements),0);
    const pockets=empty(data.pockets).filter(p=>p.createdDate<=today&&accounts.some(a=>a.id===p.parentAccountId&&['debit','cash'].includes(a.type)));
    const reserve=Math.max(0,deps.Pockets.totalAllocated(pockets,empty(data.pocketMoves).filter(m=>m.date<=today),movements));
    let cardsDue=0,recurringDue=0,missingDue=0;
    const warnings=[];
    for(const card of accounts.filter(a=>a.type==='credit')){
      const all=deps.Billing.effectiveCycles(card,empty(data.billingCycles));
      for(const c of all){
        const remaining=deps.Billing.officialRemaining(card,c,movements,all);
        if(!(remaining>0))continue;
        if(c.dueDate&&validDate(c.dueDate)){
          if(c.dueDate<=end)cardsDue+=remaining; // incluye vencidos anteriores a hoy
        }else missingDue++;
      }
      if(!all.some(c=>c.amountDue!=null)&&deps.F.accountBalance(card,movements)>0)missingDue++;
    }
    const sourceMonths=new Set([today.slice(0,7),end.slice(0,7)]);
    for(const month of sourceMonths){
      for(const e of occurrences(data,deps.Rec,month)){
        if(e.status==='planned'&&e.date>=today&&e.date<=end&&e.accountType!=='credit')recurringDue+=e.amount;
      }
    }
    // El mismo cargo generado no se cuenta otra vez como regla programada.
    for(const m of empty(data.movements)){
      if(m.type==='expense'&&m.autoGenerated&&!m.confirmed&&validDate(m.date)&&m.date<=end&&
          accounts.some(a=>a.id===m.accountId&&a.type!=='credit'))recurringDue+=m.amount;
    }
    if(missingDue)warnings.push('Hay '+missingDue+' corte(s) o deuda(s) sin fecha o importe suficiente: no están incluidos en el cálculo de obligaciones.');
    if(accounts.some(a=>['debit','cash'].includes(a.type)&&a.balanceDate>today))warnings.push('Algunas cuentas tienen fecha base posterior a hoy; se excluyeron de la liquidez.');
    if(accounts.some(a=>a.type==='credit'))warnings.push('Compras futuras a crédito sin corte confirmado y gastos no registrados no se incluyen.');
    const available=liquid-reserve-cardsDue-recurringDue;
    return {today,end,days,liquid,reservedPockets:reserve,cardsDue,recurringDue,obligations:cardsDue+recurringDue,
      available:Math.max(0,available),shortfall:Math.max(0,-available),warnings};
  }
  return {plusDays,monthEnd,occurrences,calendar,capacity};
});
