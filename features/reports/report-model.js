/* Reports v0.12: fact-only historical series. Every amount is integer MXN cents. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.FinanceReportModel=api;})(typeof globalThis!=='undefined'?globalThis:this,()=>{
'use strict';
const monthPattern=/^\d{4}-(0[1-9]|1[0-2])$/;
const dayPattern=/^\d{4}-(0[1-9]|1[0-2])-\d{2}$/;
const isActive=m=>!(m.autoGenerated&&!m.confirmed);
const sum=(a,k)=>a.reduce((s,x)=>s+(Number(x[k])||0),0);
function endOf(month){const [y,m]=month.split('-').map(Number);return month+'-'+String(new Date(y,m,0).getDate()).padStart(2,'0');}
function assemble({F,accounts=[],movements=[],cycles=[],month,range=6,accountId='all',today}){
 if(!monthPattern.test(month)||!dayPattern.test(today)||![3,6,12].includes(range))throw Error('Periodo inválido para informes.');
 const chosen=accountId==='all'?accounts:accounts.filter(a=>a.id===accountId);
 const known=accountId==='all'||chosen.length===1;
 if(!known)throw Error('La cuenta filtrada no existe.');
 const ids=new Set(chosen.map(a=>a.id));
 const cutoff=movements.filter(m=>isActive(m)&&typeof m.date==='string'&&m.date<=today);
 const filtered=cutoff.filter(m=>ids.has(m.accountId)||m.toAccountId&&ids.has(m.toAccountId));
 const months=Array.from({length:range},(_,i)=>F.shiftMonth(month,i-range+1));
 const rows=months.map(key=>{
   const b=F.breakdown(chosen,filtered,key,cycles);
   const through=key>today.slice(0,7)?null:key===today.slice(0,7)?today:endOf(key);
   const hasBasis=Boolean(through)&&chosen.length>0&&chosen.every(a=>a.balanceDate&&a.balanceDate<=through);
   const snapshot=hasBasis?F.totals(chosen,filtered.filter(m=>m.date<=through)):null;
   return {month:key,income:b.income,yields:b.yields,purchases:b.purchases,bankOutflow:b.bankOutflow,
     payments:b.cardPayments,cashChange:b.cashChange,assets:snapshot?.assets??null,
     debts:snapshot?.debts??null,netWorth:snapshot?.netWorth??null,complete:hasBasis,
     partial:through===today,asOf:through};
 });
 const chosenMonth=rows[rows.length-1];
 const breakdown=F.breakdown(chosen,filtered,month,cycles);
 const categories=Object.entries(breakdown.byCat).filter(([,value])=>value>0).sort((a,b)=>b[1]-a[1])
  .map(([name,amount])=>({name,amount,percent:breakdown.purchases?Math.round(1000*amount/breakdown.purchases)/10:0}));
 const items=filtered.filter(m=>m.type==='expense'&&F.monthlyPurchaseMonth(m,chosen.find(a=>a.id===m.accountId),cycles)===month)
  .sort((a,b)=>b.date.localeCompare(a.date));
 const cards=chosen.filter(a=>a.type==='credit').map(card=>({
   id:card.id,name:card.name,initialDebt:card.initialDebt||0,
   balance:card.balanceDate<=today?F.accountBalance(card,filtered.filter(m=>m.date<=today)):null,
   payments:filtered.filter(m=>m.type==='payment'&&m.toAccountId===card.id&&m.date.startsWith(month)).reduce((v,m)=>v+m.amount,0)
 }));
 return {month,range,accountId,selectedName:accountId==='all'?'Todas las cuentas':chosen[0]?.name||'',
   rows,current:chosenMonth,categories,items,cards,hasAccounts:chosen.length>0,
   monthPurchases:breakdown.purchases,totalIncome:sum(rows,'income'),totalPurchases:sum(rows,'purchases'),
   selectedIsFuture:month>today.slice(0,7),today};
}
return {assemble,endOf,isActive};
});